#include<stdio.h>
int main()
{
    int A = 15;
    int B = 10;

    printf("A+B = %d\n", A+B);//25
    printf("A-b = %d\n", A-B);//5
    printf("A*B = %d\n", A*B);//150
    printf("A/B = %d\n", A/B);//1
    printf("A%b = %d\n", A%B);//5

    int X=5;
    ++X;
    printf("%d\n", X);//6
    --X;
    printf("%d\n", X);//5
    return 0;

}
