#include<stdio.h>
int main()
{
    int x =10;
    int y = 5;
    printf("%d\n", x>y); //return 1(true) because 10 is greater than 5
    printf("%d\n", x<y); // return 0(false) because 10 is greater than 5

    int distance = 20;
    printf("%d\n", distance >= 20);//return 1
    printf("%d\n", distance < 20);//return 0

    float height = 6;
    printf("%d\n", height >=10);//return 0
    printf("%d\n", height <10);//return 1

}
